// Tests for check-tauri-versions.mjs, on lockfile fixtures written inline and on
// the repository's own lockfiles.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';

import { ROOT, cargoVersions, mismatches, npmName, npmVersions } from './check-tauri-versions.mjs';

// The pair every real lockfile pair holds, added to a fixture that does not name it.
const TAURI = ['tauri', '2.12.5'];
const API = ['@tauri-apps/api', '2.12.4'];

/** A Cargo.lock holding these name/version pairs, `tauri` among them unless `bare`. */
function cargoLock(pairs, { format = 4, bare = false } = {}) {
  const all = bare || pairs.some(([n]) => n === 'tauri') ? pairs : [TAURI, ...pairs];
  const blocks = all.map(
    ([name, version]) =>
      `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`
  );
  return `# This file is automatically @generated by Cargo.\nversion = ${format}\n\n${blocks.join('\n')}`;
}

/**
 * A pnpm-lock.yaml whose root project depends on these name/version pairs,
 * `@tauri-apps/api` among them unless `bare`, and another project on `other`.
 */
function pnpmLock(pairs, { other = [], format = '9.0', bare = false, root = '.' } = {}) {
  const all = bare || pairs.some(([n]) => n === API[0]) ? pairs : [API, ...pairs];
  const deps = ps =>
    ps
      .map(([name, version]) => `      '${name}':\n        specifier: ^${version}\n        version: ${version}\n`)
      .join('');
  return [
    `lockfileVersion: '${format}'`,
    '',
    'importers:',
    '',
    `  ${root}:`,
    '    dependencies:',
    deps(all) + (other.length ? '  packages/other:\n    dependencies:\n' + deps(other) : '') + 'packages:',
    '',
    "  '@tauri-apps/api@9.9.9':",
    '    resolution: {integrity: sha512-x}',
    ''
  ].join('\n');
}

test('crates and packages on one major.minor pass, whatever their patch', () => {
  const cargo = cargoLock([
    ['tauri', '2.12.5'],
    ['tauri-plugin-dialog', '2.8.4'],
    ['serde', '1.0.0']
  ]);
  const npm = pnpmLock([
    ['@tauri-apps/api', '2.12.0'],
    ['@tauri-apps/plugin-dialog', '2.8.3'],
    ['react', '19.3.0']
  ]);
  assert.deepEqual(mismatches(cargo, npm), []);
});

test('a plugin a minor apart is a mismatch, as tauri build has it', () => {
  const cargo = cargoLock([['tauri-plugin-notification', '2.8.0']]);
  const npm = pnpmLock([['@tauri-apps/plugin-notification', '2.7.0']]);
  assert.deepEqual(mismatches(cargo, npm), [
    'tauri-plugin-notification 2.8.0 (Cargo.lock) and @tauri-apps/plugin-notification 2.7.0 (pnpm-lock.yaml) differ in major.minor'
  ]);
});

test('tauri itself goes with @tauri-apps/api, and a major apart is a mismatch too', () => {
  const found = mismatches(cargoLock([['tauri', '3.0.1']]), pnpmLock([['@tauri-apps/api', '2.0.1']]));
  assert.equal(found.length, 1);
  assert.match(found[0], /^tauri 3\.0\.1 .* @tauri-apps\/api 2\.0\.1 /);
});

test('a plugin with no other half is not compared', () => {
  const cargo = cargoLock([['tauri-plugin-single-instance', '2.5.5']]);
  const npm = pnpmLock([['@tauri-apps/plugin-shell', '1.0.0']]);
  assert.deepEqual(mismatches(cargo, npm), []);
  assert.equal(npmName('tauri-build'), null);
  assert.equal(npmName('tauri-plugin-dialog'), '@tauri-apps/plugin-dialog');
});

test('only the root project is read from pnpm-lock, its peers suffix dropped', () => {
  const npm = npmVersions(
    pnpmLock([['@xterm/addon-fit', '0.10.0(@xterm/xterm@5.5.0)']], { other: [['@tauri-apps/plugin-fs', '1.0.0']] })
  );
  assert.deepEqual(
    [...npm],
    [
      ['@tauri-apps/api', '2.12.4'],
      ['@xterm/addon-fit', '0.10.0']
    ]
  );
});

test('every locked version of a crate is compared', () => {
  const cargo = cargoLock([
    ['tauri-plugin-fs', '2.7.1'],
    ['tauri-plugin-fs', '2.6.0']
  ]);
  assert.deepEqual(cargoVersions(cargo).get('tauri-plugin-fs'), ['2.7.1', '2.6.0']);
  assert.equal(mismatches(cargo, pnpmLock([['@tauri-apps/plugin-fs', '2.7.0']])).length, 1);
});

test('Cargo.lock formats 3 and 4 are read, and nothing else', () => {
  assert.deepEqual(mismatches(cargoLock([], { format: 3 }), pnpmLock([])), []);
  assert.throws(() => cargoVersions(cargoLock([], { format: 2 })), /Cargo\.lock: format version 2/);
  assert.throws(
    () => cargoVersions('[[package]]\nname = "tauri"\nversion = "2.0.0"\n'),
    /Cargo\.lock: no format version/
  );
});

test('a Cargo.lock whose packages do not read is refused, not passed', () => {
  assert.throws(() => cargoVersions('version = 4\n'), /Cargo\.lock: no \[\[package\]\]/);
  assert.throws(
    () => cargoVersions('version = 4\n\n[[package]]\nname = "tauri"\nversion = 2\n'),
    /Cargo\.lock: a \[\[package\]\] without a name and version/
  );
});

test('a pnpm-lock of another lockfileVersion, or with no root project, is refused', () => {
  assert.throws(() => npmVersions(pnpmLock([], { format: '6.0' })), /pnpm-lock\.yaml: lockfileVersion '6\.0'/);
  assert.throws(() => npmVersions('importers:\n\n  .:\n'), /pnpm-lock\.yaml: no lockfileVersion/);
  assert.throws(() => npmVersions(pnpmLock([], { root: 'app' })), /pnpm-lock\.yaml: no root project/);
});

test('lockfiles without the tauri and @tauri-apps/api pair are refused', () => {
  assert.throws(
    () => mismatches(cargoLock([['serde', '1.0.0']], { bare: true }), pnpmLock([])),
    /no tauri in Cargo\.lock/
  );
  assert.throws(
    () => mismatches(cargoLock([]), pnpmLock([['react', '19.3.0']], { bare: true })),
    /no @tauri-apps\/api in pnpm-lock\.yaml/
  );
});

test("the repository's own lockfiles agree", () => {
  const cargo = readFileSync(join(ROOT, 'src-tauri', 'Cargo.lock'), 'utf8');
  const npm = readFileSync(join(ROOT, 'pnpm-lock.yaml'), 'utf8');
  assert.ok(cargoVersions(cargo).has('tauri'), 'the tauri crate is read');
  assert.ok(npmVersions(npm).has('@tauri-apps/api'), 'the root project is read');
  assert.deepEqual(mismatches(cargo, npm), []);
});
