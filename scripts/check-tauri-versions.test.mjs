// Tests for check-tauri-versions.mjs, on lockfile fixtures written inline and on
// the repository's own lockfiles.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';

import { ROOT, cargoVersions, mismatches, npmName, npmVersions } from './check-tauri-versions.mjs';

/** A Cargo.lock holding these name/version pairs. */
function cargoLock(pairs) {
  const blocks = pairs.map(
    ([name, version]) =>
      `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`
  );
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n${blocks.join('\n')}`;
}

/** A pnpm-lock.yaml whose root project depends on these name/version pairs. */
function pnpmLock(pairs, other = []) {
  const deps = ps =>
    ps
      .map(([name, version]) => `      '${name}':\n        specifier: ^${version}\n        version: ${version}\n`)
      .join('');
  return [
    "lockfileVersion: '9.0'",
    '',
    'importers:',
    '',
    '  .:',
    '    dependencies:',
    deps(pairs) + (other.length ? '  packages/other:\n    dependencies:\n' + deps(other) : '') + 'packages:',
    '',
    "  '@tauri-apps/api@9.9.9':",
    '    resolution: {integrity: sha512-x}',
    ''
  ].join('\n');
}

test('crates and packages on one major.minor pass, whatever their patch', () => {
  const cargo = cargoLock([
    ['tauri', '2.12.5'],
    ['tauri-plugin-dialog', '2.8.4'],
    ['serde', '1.0.0']
  ]);
  const npm = pnpmLock([
    ['@tauri-apps/api', '2.12.0'],
    ['@tauri-apps/plugin-dialog', '2.8.3'],
    ['react', '19.3.0']
  ]);
  assert.deepEqual(mismatches(cargo, npm), []);
});

test('a plugin a minor apart is a mismatch, as tauri build has it', () => {
  const cargo = cargoLock([
    ['tauri', '2.12.5'],
    ['tauri-plugin-notification', '2.8.0']
  ]);
  const npm = pnpmLock([
    ['@tauri-apps/api', '2.12.4'],
    ['@tauri-apps/plugin-notification', '2.7.0']
  ]);
  assert.deepEqual(mismatches(cargo, npm), [
    'tauri-plugin-notification 2.8.0 (Cargo.lock) and @tauri-apps/plugin-notification 2.7.0 (pnpm-lock.yaml) differ in major.minor'
  ]);
});

test('tauri itself goes with @tauri-apps/api, and a major apart is a mismatch too', () => {
  const found = mismatches(cargoLock([['tauri', '3.0.1']]), pnpmLock([['@tauri-apps/api', '2.0.1']]));
  assert.equal(found.length, 1);
  assert.match(found[0], /^tauri 3\.0\.1 .* @tauri-apps\/api 2\.0\.1 /);
});

test('a side with no other half is not compared', () => {
  const cargo = cargoLock([['tauri-plugin-single-instance', '2.5.5']]);
  const npm = pnpmLock([['@tauri-apps/plugin-shell', '1.0.0']]);
  assert.deepEqual(mismatches(cargo, npm), []);
  assert.equal(npmName('tauri-build'), null);
  assert.equal(npmName('tauri-plugin-dialog'), '@tauri-apps/plugin-dialog');
});

test('only the root project is read from pnpm-lock, its peers suffix dropped', () => {
  const npm = npmVersions(
    pnpmLock([['@xterm/addon-fit', '0.10.0(@xterm/xterm@5.5.0)']], [['@tauri-apps/api', '1.0.0']])
  );
  assert.deepEqual([...npm], [['@xterm/addon-fit', '0.10.0']]);
});

test('every locked version of a crate is compared', () => {
  const cargo = cargoLock([
    ['tauri-plugin-fs', '2.7.1'],
    ['tauri-plugin-fs', '2.6.0']
  ]);
  assert.deepEqual(cargoVersions(cargo).get('tauri-plugin-fs'), ['2.7.1', '2.6.0']);
  assert.equal(mismatches(cargo, pnpmLock([['@tauri-apps/plugin-fs', '2.7.0']])).length, 1);
});

test("the repository's own lockfiles agree", () => {
  const cargo = readFileSync(join(ROOT, 'src-tauri', 'Cargo.lock'), 'utf8');
  const npm = readFileSync(join(ROOT, 'pnpm-lock.yaml'), 'utf8');
  assert.ok(npmVersions(npm).has('@tauri-apps/api'), 'the root project is read');
  assert.deepEqual(mismatches(cargo, npm), []);
});
